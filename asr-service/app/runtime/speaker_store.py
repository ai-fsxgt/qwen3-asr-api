"""PostgreSQL + pgvector 声纹库存储。

该模块是声纹数据的唯一持久化边界：上层只处理说话人、模板和识别结果，
不感知 SQL。所有实例直接查询同一 PostgreSQL，不维护进程内全量声纹缓存，
因此多服务写入后立即可见，也不存在缓存同步问题。

全部方法均为同步方法。FastAPI 路由和转写流程必须在线程池中调用，避免
阻塞事件循环。连接由 psycopg 线程安全连接池管理，写操作使用显式事务。
"""
from __future__ import annotations

import logging
import math
import uuid
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime, timezone

import numpy as np
import psycopg
from pgvector.psycopg import register_vector
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb
from psycopg_pool import ConnectionPool

logger = logging.getLogger(__name__)


_SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS speaker_meta (
      key   TEXT PRIMARY KEY,
      value TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS speakers (
      id         TEXT PRIMARY KEY,
      name       TEXT NOT NULL,
      note       TEXT,
      consent    BOOLEAN NOT NULL CHECK (consent),
      source     TEXT NOT NULL DEFAULT 'manual',
      model_tag  TEXT NOT NULL,
      centroid   vector(192),
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS speaker_templates (
      id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      speaker_id TEXT NOT NULL REFERENCES speakers(id) ON DELETE CASCADE,
      vector     vector(192) NOT NULL,
      dur_sec    DOUBLE PRECISION NOT NULL CHECK (dur_sec >= 0),
      created_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_speaker_templates_speaker
      ON speaker_templates(speaker_id)
    """,
    """
    CREATE TABLE IF NOT EXISTS speaker_claims (
      claim_key  TEXT PRIMARY KEY,
      speaker_id TEXT NOT NULL REFERENCES speakers(id) ON DELETE CASCADE,
      response   JSONB NOT NULL,
      created_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_speaker_claims_speaker
      ON speaker_claims(speaker_id)
    """,
    """
    CREATE TABLE IF NOT EXISTS speaker_audit_log (
      id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ts         TIMESTAMPTZ NOT NULL,
      action     TEXT NOT NULL,
      speaker_id TEXT,
      detail     JSONB
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_speaker_audit_log_ts
      ON speaker_audit_log(ts DESC)
    """,
)


class SpeakerStoreError(Exception):
    """声纹库操作失败。"""


class SpeakerNotFoundError(SpeakerStoreError):
    """目标说话人或模板不存在。"""


class SpeakerClaimConflictError(SpeakerStoreError):
    """认领目标或幂等键冲突。"""

    def __init__(
        self,
        code: str,
        message: str,
        *,
        speaker_id: str,
        speaker_name: str,
        source: str,
    ):
        super().__init__(message)
        self.code = code
        self.speaker_id = speaker_id
        self.speaker_name = speaker_name
        self.source = source


@dataclass(frozen=True)
class SpeakerIdentification:
    """一次开集识别的完整判决，供审计与阈值标定使用。"""

    matched: bool
    reason: str
    top1_score: float | None = None
    top2_score: float | None = None
    margin: float | None = None
    speaker_id: str | None = None
    name: str | None = None
    source: str | None = None

    def as_match(self, *, include_source: bool = False) -> dict | None:
        if not self.matched:
            return None
        result = {
            "speaker_id": self.speaker_id,
            "name": self.name,
            "score": self.top1_score,
        }
        if include_source:
            result["source"] = self.source
        return result


@dataclass(frozen=True)
class SpeakerAutoEnrollment:
    """跨实例自动登记结果。"""

    identification: SpeakerIdentification
    speaker_id: str | None
    name: str | None
    created: bool


class SpeakerStore:
    """共享 PostgreSQL 声纹库。"""

    SCHEMA_VERSION = 1
    DIM = 192
    MAX_TEMPLATES = 16
    MAX_CLAIM_KEY_LENGTH = 128
    _NORM_TOL = 1e-3
    _AUTO_ENROLL_LOCK = "qwen3-asr:speaker-auto-enroll"
    _SCHEMA_INIT_LOCK = "qwen3-asr:speaker-schema-init"

    def __init__(
        self,
        database_url: str,
        model_tag: str,
        *,
        pool_min_size: int = 1,
        pool_max_size: int = 4,
        pool_timeout: float = 5.0,
    ):
        if not database_url or not database_url.strip():
            raise SpeakerStoreError("未配置 PostgreSQL 连接地址")
        if pool_min_size < 1 or pool_max_size < pool_min_size:
            raise SpeakerStoreError("声纹库连接池大小配置无效")

        self.database_url = database_url
        self.model_tag = model_tag
        self._pool: ConnectionPool | None = None
        connect_timeout = max(1, math.ceil(pool_timeout))
        try:
            with self._schema_initialization_lock(database_url, connect_timeout):
                self._pool = ConnectionPool(
                    conninfo=database_url,
                    min_size=pool_min_size,
                    max_size=pool_max_size,
                    timeout=pool_timeout,
                    kwargs={
                        "autocommit": True,
                        "row_factory": dict_row,
                        "connect_timeout": connect_timeout,
                    },
                    configure=self._configure_connection,
                    open=True,
                )
                self._pool.wait(timeout=pool_timeout)
                self._initialize_schema()
        except Exception as exc:
            if self._pool is not None:
                self._pool.close()
            raise SpeakerStoreError(f"声纹库初始化失败: {exc}") from exc

        logger.info(
            "共享声纹库已启用: %s（model_tag=%s，%d 人）",
            self._safe_database_label(database_url),
            model_tag,
            self.speaker_count,
        )

    @classmethod
    @contextmanager
    def _schema_initialization_lock(
        cls,
        database_url: str,
        connect_timeout: int,
    ):
        """跨实例串行创建 vector 扩展和声纹表结构。"""
        with psycopg.connect(
            database_url,
            autocommit=True,
            connect_timeout=connect_timeout,
        ) as conn:
            conn.execute(
                "SELECT pg_advisory_lock(hashtextextended(%s, 0))",
                (cls._SCHEMA_INIT_LOCK,),
            )
            try:
                conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
                yield
            finally:
                conn.execute(
                    "SELECT pg_advisory_unlock(hashtextextended(%s, 0))",
                    (cls._SCHEMA_INIT_LOCK,),
                )

    @staticmethod
    def _configure_connection(conn: psycopg.Connection) -> None:
        register_vector(conn)

    @staticmethod
    def _safe_database_label(database_url: str) -> str:
        try:
            info = conninfo_to_dict(database_url)
        except Exception:
            return "PostgreSQL（连接信息已隐藏）"
        host = info.get("host") or "localhost"
        port = info.get("port") or "5432"
        dbname = info.get("dbname") or "postgres"
        return f"postgresql://{host}:{port}/{dbname}"

    @staticmethod
    def _now() -> datetime:
        return datetime.now(timezone.utc)

    def _connection(self):
        if self._pool is None:
            raise SpeakerStoreError("声纹库连接池已关闭")
        return self._pool.connection()

    def _initialize_schema(self) -> None:
        with self._connection() as conn:
            with conn.transaction():
                for statement in _SCHEMA_STATEMENTS:
                    conn.execute(statement)
                row = conn.execute(
                    "SELECT value FROM speaker_meta WHERE key='schema_version'"
                ).fetchone()
                if row is None:
                    conn.execute(
                        "INSERT INTO speaker_meta(key, value) VALUES(%s, %s)",
                        ("schema_version", str(self.SCHEMA_VERSION)),
                    )
                else:
                    try:
                        version = int(row["value"])
                    except (TypeError, ValueError) as exc:
                        raise SpeakerStoreError(
                            "声纹库 schema_version 无效"
                        ) from exc
                    if version != self.SCHEMA_VERSION:
                        raise SpeakerStoreError(
                            "声纹库版本不兼容: "
                            f"{version} != {self.SCHEMA_VERSION}"
                        )
                conn.execute(
                    """
                    INSERT INTO speaker_meta(key, value) VALUES(%s, %s)
                    ON CONFLICT (key) DO NOTHING
                    """,
                    ("model_tag", self.model_tag),
                )
                conn.execute(
                    """
                    INSERT INTO speaker_meta(key, value) VALUES(%s, %s)
                    ON CONFLICT (key) DO NOTHING
                    """,
                    ("created_at", self._now().isoformat()),
                )

    def _validate_vector(self, vector: np.ndarray) -> np.ndarray:
        value = np.asarray(vector, dtype=np.float32).reshape(-1)
        if value.shape[0] != self.DIM:
            raise SpeakerStoreError(
                f"向量维度须为 {self.DIM}，实得 {value.shape[0]}"
            )
        norm = float(np.linalg.norm(value))
        if not np.isfinite(norm) or abs(norm - 1.0) > self._NORM_TOL:
            raise SpeakerStoreError(f"向量须 L2 归一（norm={norm:.4f}）")
        return value

    @staticmethod
    def _normalize_mean(vectors: list[np.ndarray]) -> np.ndarray:
        centroid = np.stack(vectors).mean(axis=0)
        norm = float(np.linalg.norm(centroid))
        if not np.isfinite(norm) or norm <= 0:
            raise SpeakerStoreError("模板质心无法归一化")
        return (centroid / norm).astype(np.float32)

    @staticmethod
    def _validate_durations(durations: list[float]) -> list[float]:
        try:
            values = [float(duration) for duration in durations]
        except (TypeError, ValueError) as exc:
            raise SpeakerStoreError("模板时长无效") from exc
        if any(not np.isfinite(value) or value < 0 for value in values):
            raise SpeakerStoreError("模板时长无效")
        return values

    def _validate_templates(
        self,
        vectors: list[np.ndarray],
        durations: list[float],
    ) -> tuple[list[np.ndarray], list[float], np.ndarray]:
        if not vectors or len(vectors) != len(durations):
            raise SpeakerStoreError("模板向量与时长数量不符或为空")
        if len(vectors) > self.MAX_TEMPLATES:
            raise SpeakerStoreError(f"模板数超过上限 {self.MAX_TEMPLATES}")
        validated = [self._validate_vector(vector) for vector in vectors]
        valid_durations = self._validate_durations(durations)
        return validated, valid_durations, self._normalize_mean(validated)

    @staticmethod
    def _claim_conflict(row: dict) -> SpeakerClaimConflictError:
        return SpeakerClaimConflictError(
            "claim_key_conflict",
            "claim_key 已用于其他说话人",
            speaker_id=row["speaker_id"],
            speaker_name=row["name"],
            source=row["source"],
        )

    def _read_claim(
        self,
        conn: psycopg.Connection,
        speaker_id: str,
        claim_key: str,
    ) -> dict | None:
        row = conn.execute(
            """
            SELECT c.speaker_id, c.response, s.name, s.source
            FROM speaker_claims c
            JOIN speakers s ON s.id = c.speaker_id
            WHERE c.claim_key=%s
            """,
            (claim_key,),
        ).fetchone()
        if row is None:
            return None
        if row["speaker_id"] != speaker_id:
            raise self._claim_conflict(row)
        response = row["response"]
        if not isinstance(response, dict):
            raise SpeakerStoreError("认领幂等记录格式错误")
        return response

    @staticmethod
    def _require_auto_speaker(
        conn: psycopg.Connection,
        speaker_id: str,
        *,
        lock: bool = False,
    ) -> dict:
        suffix = sql.SQL(" FOR UPDATE") if lock else sql.SQL("")
        query = sql.SQL(
            "SELECT id, name, source FROM speakers WHERE id=%s"
        ) + suffix
        row = conn.execute(query, (speaker_id,)).fetchone()
        if row is None:
            raise SpeakerNotFoundError(f"说话人不存在: {speaker_id}")
        if row["source"] != "auto":
            raise SpeakerClaimConflictError(
                "speaker_not_claimable",
                "仅自动登记的说话人可以被认领",
                speaker_id=row["id"],
                speaker_name=row["name"],
                source=row["source"],
            )
        return row

    @staticmethod
    def _insert_templates(
        conn: psycopg.Connection,
        speaker_id: str,
        vectors: list[np.ndarray],
        durations: list[float],
        created_at: datetime,
    ) -> list[int]:
        template_ids = []
        for vector, duration in zip(vectors, durations, strict=True):
            row = conn.execute(
                """
                INSERT INTO speaker_templates(
                  speaker_id, vector, dur_sec, created_at
                ) VALUES(%s, %s, %s, %s)
                RETURNING id
                """,
                (speaker_id, vector, duration, created_at),
            ).fetchone()
            template_ids.append(int(row["id"]))
        return template_ids

    def _insert_speaker(
        self,
        conn: psycopg.Connection,
        name: str,
        note: str | None,
        vectors: list[np.ndarray],
        durations: list[float],
        centroid: np.ndarray,
        *,
        source: str,
    ) -> str:
        speaker_id = uuid.uuid4().hex
        now = self._now()
        conn.execute(
            """
            INSERT INTO speakers(
              id, name, note, consent, source, model_tag,
              centroid, created_at, updated_at
            ) VALUES(%s, %s, %s, TRUE, %s, %s, %s, %s, %s)
            """,
            (
                speaker_id,
                name,
                note,
                source,
                self.model_tag,
                centroid,
                now,
                now,
            ),
        )
        self._insert_templates(conn, speaker_id, vectors, durations, now)
        return speaker_id

    def _recompute_centroid(
        self,
        conn: psycopg.Connection,
        speaker_id: str,
    ) -> int:
        rows = conn.execute(
            """
            SELECT vector FROM speaker_templates
            WHERE speaker_id=%s ORDER BY id
            """,
            (speaker_id,),
        ).fetchall()
        if not rows:
            conn.execute(
                "UPDATE speakers SET centroid=NULL, updated_at=%s WHERE id=%s",
                (self._now(), speaker_id),
            )
            return 0
        vectors = [
            np.asarray(row["vector"].to_numpy(), dtype=np.float32)
            for row in rows
        ]
        conn.execute(
            "UPDATE speakers SET centroid=%s, updated_at=%s WHERE id=%s",
            (self._normalize_mean(vectors), self._now(), speaker_id),
        )
        return len(vectors)

    # ─── 写路径 ───

    def enroll_speaker(
        self,
        name: str,
        note: str | None,
        vectors: list[np.ndarray],
        durs: list[float],
        consent: bool,
        source: str = "manual",
    ) -> str:
        if consent is not True:
            raise SpeakerStoreError("登记必须携带 consent=true（数据主体同意）")
        validated, durations, centroid = self._validate_templates(vectors, durs)
        try:
            with self._connection() as conn:
                with conn.transaction():
                    speaker_id = self._insert_speaker(
                        conn,
                        name,
                        note,
                        validated,
                        durations,
                        centroid,
                        source=source,
                    )
        except SpeakerStoreError:
            raise
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"登记写入失败: {exc}") from exc
        self.audit(
            "enroll" if source == "manual" else "auto_enroll",
            speaker_id,
            {"name": name, "templates": len(validated)},
        )
        return speaker_id

    def resolve_claim(self, speaker_id: str, claim_key: str) -> dict | None:
        if not claim_key or len(claim_key) > self.MAX_CLAIM_KEY_LENGTH:
            raise SpeakerStoreError("claim_key 无效")
        try:
            with self._connection() as conn:
                replay = self._read_claim(conn, speaker_id, claim_key)
                if replay is not None:
                    return replay
                try:
                    self._require_auto_speaker(conn, speaker_id)
                except SpeakerClaimConflictError:
                    # 另一实例可能刚用同一 claim_key 完成认领：状态与幂等
                    # 记录在同一事务提交，此时重读即可区分幂等回放与真实冲突。
                    replay = self._read_claim(conn, speaker_id, claim_key)
                    if replay is not None:
                        return replay
                    raise
                return None
        except SpeakerStoreError:
            raise
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"认领状态读取失败: {exc}") from exc

    def claim_auto_speaker(
        self,
        speaker_id: str,
        name: str,
        note: str | None,
        vectors: list[np.ndarray],
        durs: list[float],
        claim_key: str,
        quality_hint: str | None = None,
    ) -> tuple[dict, bool]:
        if not claim_key or len(claim_key) > self.MAX_CLAIM_KEY_LENGTH:
            raise SpeakerStoreError("claim_key 无效")
        validated, durations, centroid = self._validate_templates(vectors, durs)
        now = self._now()
        response: dict
        try:
            with self._connection() as conn:
                with conn.transaction():
                    # 同一幂等键跨服务串行化，避免并发认领重复替换模板。
                    conn.execute(
                        "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                        (claim_key,),
                    )
                    replay = self._read_claim(conn, speaker_id, claim_key)
                    if replay is not None:
                        return replay, False
                    self._require_auto_speaker(conn, speaker_id, lock=True)

                    conn.execute(
                        "DELETE FROM speaker_templates WHERE speaker_id=%s",
                        (speaker_id,),
                    )
                    template_ids = self._insert_templates(
                        conn, speaker_id, validated, durations, now
                    )
                    conn.execute(
                        """
                        UPDATE speakers
                        SET name=%s, note=%s, consent=TRUE, source='manual',
                            centroid=%s, updated_at=%s
                        WHERE id=%s
                        """,
                        (name, note, centroid, now, speaker_id),
                    )
                    response = {
                        "speaker_id": speaker_id,
                        "name": name,
                        "source": "manual",
                        "templates": len(template_ids),
                        "template_ids": template_ids,
                        "quality_hint": quality_hint,
                    }
                    conn.execute(
                        """
                        INSERT INTO speaker_claims(
                          claim_key, speaker_id, response, created_at
                        ) VALUES(%s, %s, %s, %s)
                        """,
                        (claim_key, speaker_id, Jsonb(response), now),
                    )
        except SpeakerStoreError:
            raise
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"说话人认领失败: {exc}") from exc

        self.audit(
            "claim",
            speaker_id,
            {"name": name, "templates": len(validated)},
        )
        return response, True

    @staticmethod
    def _allocate_auto_name(conn: psycopg.Connection) -> str:
        row = conn.execute(
            """
            INSERT INTO speaker_meta(key, value)
            VALUES('auto_name_seq', '1')
            ON CONFLICT (key) DO UPDATE
            SET value=(speaker_meta.value::BIGINT + 1)::TEXT
            RETURNING value
            """
        ).fetchone()
        return f"说话人_{int(row['value']):02d}"

    def alloc_auto_name(self) -> str:
        try:
            with self._connection() as conn:
                return self._allocate_auto_name(conn)
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"占位名序号分配失败: {exc}") from exc

    def add_template(
        self,
        speaker_id: str,
        vector: np.ndarray,
        dur: float,
    ) -> None:
        validated = self._validate_vector(vector)
        duration = self._validate_durations([dur])[0]
        try:
            with self._connection() as conn:
                with conn.transaction():
                    speaker = conn.execute(
                        "SELECT id FROM speakers WHERE id=%s FOR UPDATE",
                        (speaker_id,),
                    ).fetchone()
                    if speaker is None:
                        raise SpeakerNotFoundError(
                            f"说话人不存在: {speaker_id}"
                        )
                    count = conn.execute(
                        """
                        SELECT COUNT(*) AS count FROM speaker_templates
                        WHERE speaker_id=%s
                        """,
                        (speaker_id,),
                    ).fetchone()["count"]
                    if count >= self.MAX_TEMPLATES:
                        raise SpeakerStoreError(
                            f"模板数已达上限 {self.MAX_TEMPLATES}"
                        )
                    self._insert_templates(
                        conn,
                        speaker_id,
                        [validated],
                        [duration],
                        self._now(),
                    )
                    self._recompute_centroid(conn, speaker_id)
        except SpeakerStoreError:
            raise
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"模板追加失败: {exc}") from exc
        self.audit("add_template", speaker_id, {"dur_sec": duration})

    def delete_template(self, speaker_id: str, template_id: int) -> int:
        try:
            with self._connection() as conn:
                with conn.transaction():
                    speaker = conn.execute(
                        "SELECT id FROM speakers WHERE id=%s FOR UPDATE",
                        (speaker_id,),
                    ).fetchone()
                    if speaker is None:
                        raise SpeakerNotFoundError(
                            f"说话人不存在: {speaker_id}"
                        )
                    deleted = conn.execute(
                        """
                        DELETE FROM speaker_templates
                        WHERE id=%s AND speaker_id=%s RETURNING id
                        """,
                        (template_id, speaker_id),
                    ).fetchone()
                    if deleted is None:
                        raise SpeakerNotFoundError(
                            f"模板不存在: {speaker_id}/{template_id}"
                        )
                    remaining = self._recompute_centroid(conn, speaker_id)
        except SpeakerStoreError:
            raise
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"模板删除失败: {exc}") from exc
        self.audit("delete_template", speaker_id, {"template_id": template_id})
        return remaining

    def update_speaker(
        self,
        speaker_id: str,
        name: str | None = None,
        note: str | None = None,
    ) -> None:
        assignments = []
        values = []
        if name is not None:
            assignments.append(sql.SQL("name=%s"))
            values.append(name)
        if note is not None:
            assignments.append(sql.SQL("note=%s"))
            values.append(note)
        if not assignments:
            return
        assignments.append(sql.SQL("updated_at=%s"))
        values.extend([self._now(), speaker_id])
        statement = sql.SQL("UPDATE speakers SET {} WHERE id=%s RETURNING id").format(
            sql.SQL(", ").join(assignments)
        )
        try:
            with self._connection() as conn:
                row = conn.execute(statement, values).fetchone()
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"说话人更新失败: {exc}") from exc
        if row is None:
            raise SpeakerNotFoundError(f"说话人不存在: {speaker_id}")
        self.audit("update", speaker_id, {"renamed": name is not None})

    def delete_speaker(self, speaker_id: str) -> None:
        try:
            with self._connection() as conn:
                row = conn.execute(
                    "DELETE FROM speakers WHERE id=%s RETURNING id",
                    (speaker_id,),
                ).fetchone()
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"说话人删除失败: {exc}") from exc
        if row is None:
            raise SpeakerNotFoundError(f"说话人不存在: {speaker_id}")
        self.audit("delete", speaker_id)

    def audit(
        self,
        action: str,
        speaker_id: str | None = None,
        detail: dict | None = None,
    ) -> None:
        """审计是旁路，写入失败不阻断主业务。"""
        try:
            with self._connection() as conn:
                conn.execute(
                    """
                    INSERT INTO speaker_audit_log(
                      ts, action, speaker_id, detail
                    ) VALUES(%s, %s, %s, %s)
                    """,
                    (
                        self._now(),
                        action,
                        speaker_id,
                        Jsonb(detail) if detail is not None else None,
                    ),
                )
        except Exception as exc:
            logger.warning("声纹库审计写入失败（业务不受影响）: %s", exc)

    # ─── 读路径 ───

    def list_speakers(self) -> list[dict]:
        try:
            with self._connection() as conn:
                rows = conn.execute(
                    """
                    SELECT s.id, s.name, s.note, s.source,
                           s.created_at, s.updated_at,
                           COUNT(t.id) AS template_count
                    FROM speakers s
                    LEFT JOIN speaker_templates t ON t.speaker_id = s.id
                    GROUP BY s.id
                    ORDER BY s.created_at DESC
                    """
                ).fetchall()
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"说话人列表读取失败: {exc}") from exc
        return list(rows)

    def get_speaker(self, speaker_id: str) -> dict | None:
        try:
            with self._connection() as conn:
                rows = conn.execute(
                    """
                    SELECT s.id, s.name, s.note, s.source, s.model_tag,
                           s.created_at, s.updated_at,
                           t.id AS template_id,
                           t.dur_sec AS template_dur_sec,
                           t.created_at AS template_created_at
                    FROM speakers s
                    LEFT JOIN speaker_templates t ON t.speaker_id = s.id
                    WHERE s.id=%s
                    ORDER BY t.id
                    """,
                    (speaker_id,),
                ).fetchall()
                if not rows:
                    return None
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"说话人详情读取失败: {exc}") from exc
        first = rows[0]
        result = {
            key: first[key]
            for key in (
                "id",
                "name",
                "note",
                "source",
                "model_tag",
                "created_at",
                "updated_at",
            )
        }
        result["templates"] = [
            {
                "id": row["template_id"],
                "dur_sec": row["template_dur_sec"],
                "created_at": row["template_created_at"],
            }
            for row in rows
            if row["template_id"] is not None
        ]
        return result

    def identify_detailed(
        self,
        emb: np.ndarray,
        threshold: float = 0.45,
        margin: float = 0.10,
    ) -> SpeakerIdentification:
        vector = self._validate_vector(emb)
        try:
            with self._connection() as conn:
                return self._identify_with_connection(
                    conn,
                    vector,
                    threshold=threshold,
                    margin=margin,
                )
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"声纹识别查询失败: {exc}") from exc

    def _identify_with_connection(
        self,
        conn: psycopg.Connection,
        vector: np.ndarray,
        *,
        threshold: float,
        margin: float,
    ) -> SpeakerIdentification:
        rows = conn.execute(
            """
            SELECT id, name, source,
                   1 - (centroid <=> %s) AS score
            FROM speakers
            WHERE model_tag=%s AND centroid IS NOT NULL
            ORDER BY centroid <=> %s
            LIMIT 2
            """,
            (vector, self.model_tag, vector),
        ).fetchall()
        if not rows:
            return SpeakerIdentification(False, "empty_library")
        top1 = float(rows[0]["score"])
        top2 = float(rows[1]["score"]) if len(rows) > 1 else None
        score_margin = top1 - top2 if top2 is not None else None
        if top1 < threshold:
            return SpeakerIdentification(
                False,
                "below_threshold",
                top1_score=top1,
                top2_score=top2,
                margin=score_margin,
            )
        if score_margin is not None and score_margin < margin:
            return SpeakerIdentification(
                False,
                "ambiguous_margin",
                top1_score=top1,
                top2_score=top2,
                margin=score_margin,
            )
        return SpeakerIdentification(
            True,
            "matched",
            top1_score=top1,
            top2_score=top2,
            margin=score_margin,
            speaker_id=rows[0]["id"],
            name=rows[0]["name"],
            source=rows[0]["source"],
        )

    def identify_or_enroll_auto(
        self,
        emb: np.ndarray,
        dur_sec: float,
        *,
        threshold: float,
        margin: float,
    ) -> SpeakerAutoEnrollment:
        """跨实例串行执行二次识别，仍未命中时原子自动登记。"""
        vector = self._validate_vector(emb)
        duration = self._validate_durations([dur_sec])[0]
        try:
            with self._connection() as conn:
                with conn.transaction():
                    conn.execute(
                        "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                        (self._AUTO_ENROLL_LOCK,),
                    )
                    identification = self._identify_with_connection(
                        conn,
                        vector,
                        threshold=threshold,
                        margin=margin,
                    )
                    if identification.matched:
                        if (
                            identification.speaker_id is None
                            or identification.name is None
                        ):
                            raise SpeakerStoreError("声纹识别结果缺少说话人信息")
                        result = SpeakerAutoEnrollment(
                            identification=identification,
                            speaker_id=identification.speaker_id,
                            name=identification.name,
                            created=False,
                        )
                    elif identification.reason == "ambiguous_margin":
                        # 与多个已有档案过于接近时宁可保持匿名，
                        # 避免新增近似档案后进一步压缩 top1-top2 margin。
                        result = SpeakerAutoEnrollment(
                            identification=identification,
                            speaker_id=None,
                            name=None,
                            created=False,
                        )
                    else:
                        name = self._allocate_auto_name(conn)
                        speaker_id = self._insert_speaker(
                            conn,
                            name,
                            None,
                            [vector],
                            [duration],
                            vector,
                            source="auto",
                        )
                        result = SpeakerAutoEnrollment(
                            identification=identification,
                            speaker_id=speaker_id,
                            name=name,
                            created=True,
                        )
        except SpeakerStoreError:
            raise
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"自动登记失败: {exc}") from exc

        if result.created:
            self.audit(
                "auto_enroll",
                result.speaker_id,
                {"name": result.name, "templates": 1},
            )
        return result

    def identify(
        self,
        emb: np.ndarray,
        threshold: float = 0.45,
        margin: float = 0.10,
        *,
        include_source: bool = False,
    ) -> dict | None:
        return self.identify_detailed(
            emb,
            threshold=threshold,
            margin=margin,
        ).as_match(include_source=include_source)

    # ─── 启动检查 / 状态 / 收尾 ───

    def check_model_tag(self, engine_tag: str) -> bool:
        try:
            with self._connection() as conn:
                row = conn.execute(
                    "SELECT value FROM speaker_meta WHERE key='model_tag'"
                ).fetchone()
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"model_tag 读取失败: {exc}") from exc
        return row is not None and row["value"] == engine_tag

    @property
    def speaker_count(self) -> int:
        try:
            with self._connection() as conn:
                row = conn.execute(
                    "SELECT COUNT(*) AS count FROM speakers"
                ).fetchone()
        except psycopg.Error as exc:
            raise SpeakerStoreError(f"说话人数读取失败: {exc}") from exc
        return int(row["count"])

    def health(self) -> dict:
        try:
            with self._connection() as conn:
                row = conn.execute(
                    "SELECT COUNT(*) AS count FROM speakers"
                ).fetchone()
                speaker_count = int(row["count"])
        except Exception as exc:
            return {"healthy": False, "backend": "pgvector", "error": str(exc)}
        return {
            "healthy": True,
            "backend": "pgvector",
            "speaker_count": speaker_count,
        }

    def close(self) -> None:
        pool, self._pool = self._pool, None
        if pool is not None:
            pool.close()
